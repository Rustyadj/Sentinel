import { test, expect } from "@playwright/test";
import { PrismaClient } from "@prisma/client";
import bcrypt from "bcryptjs";
// This suite deliberately requires an explicitly supplied isolated test database and a separately started app.
const url = process.env.SENTINEL_OPERATIONAL_E2E_DATABASE_URL ?? "";
if (!/^postgresql:\/\/.*@(127\.0\.0\.1|localhost):\d+\/[^?]*test/.test(url)) throw new Error("Provide an isolated localhost SENTINEL_OPERATIONAL_E2E_DATABASE_URL");
const db = new PrismaClient({ datasourceUrl: url });
let workspaceId: string;
test.beforeAll(async () => {
  const user = await db.user.upsert({ where: { email: "operational-browser@synthetic.test" }, create: { email: "operational-browser@synthetic.test", passwordHash: await bcrypt.hash("synthetic-browser-test", 10) }, update: {} });
  const workspace = await db.workspace.create({ data: { slug: `synthetic-operations-browser-${Date.now()}`, name: "SYNTHETIC operations browser", ownerId: user.id } });
  workspaceId = workspace.id;
});
test.afterAll(() => db.$disconnect());
test.setTimeout(120000);
test("existing graph lenses render empty evidence, ingest an incident, and preserve navigation", async ({ page }) => {
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("/auth/signin");
  await page.getByPlaceholder("Email").fill("operational-browser@synthetic.test");
  await page.getByPlaceholder("Password").fill("synthetic-browser-test");
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await page.waitForURL(url => !url.pathname.startsWith("/auth/signin"));
  await page.goto("/graph");
  await expect(page.getByLabel("Operational lens")).toBeVisible();
  await page.getByLabel("Operational lens").selectOption("incident");
  await page.getByLabel("Operational workspace").selectOption(workspaceId);
  await expect(page.getByText("No operational evidence recorded in this workspace.")).toBeVisible();
  const fixture = { source: "synthetic-browser", sourceEventId: "synthetic-browser-incident-1", eventTime: "2026-09-01T00:00:00Z", evidence: ["https://synthetic.test/browser-evidence"], entities: [{ sourceId: "browser-service", type: "Service", title: "SYNTHETIC browser service", facts: { status: "unknown" } }, { sourceId: "browser-incident", type: "Incident", title: "SYNTHETIC browser incident", summary: "SYNTHETIC service outage from pool exhaustion", facts: { startedAt: "2026-09-01T00:00:00Z", status: "resolved", rootCauseConfirmed: false } }], relationships: [{ from: "browser-service", to: "browser-incident", type: "SERVICE_AFFECTED_BY_INCIDENT", confidence: 0.9, evidence: ["https://synthetic.test/browser-evidence"], validFrom: "2026-09-01T00:00:00Z" }] };
  const response = await page.request.post("/api/graph/operations", { data: { action: "ingest", workspaceId, event: fixture } });
  expect(response.ok()).toBe(true);
  await page.getByLabel("Operational lens").selectOption("onboarding");
  await expect.poll(async () => (await page.request.get(`/api/graph/operations?workspaceId=${workspaceId}&lens=onboarding`)).json().then(body => body.totalVisible)).toBe(2);
  await page.getByLabel("Operational lens").selectOption("blast-radius");
  await expect(page.getByLabel("Failed service").getByRole("option", { name: "SYNTHETIC browser service" })).toBeAttached();
  await page.getByLabel("Failed service").selectOption({ label: "SYNTHETIC browser service" });
  await expect(page.getByText(/Confirmed: observed failure/)).toBeVisible();
  await expect(page.getByRole("status")).toHaveCount(0);
  await expect(page.getByText("2 nodes", { exact: true })).toBeVisible();
  await expect(page.locator("canvas").first()).toBeVisible();
  await page.screenshot({ path: "test-results/operational-graph-desktop.png" });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByLabel("Operational lens")).toBeVisible();
  await page.screenshot({ path: "test-results/operational-graph-mobile.png" });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto("/memory");
  await page.getByLabel("Operational lens").selectOption("incident");
  await page.getByLabel("Operational workspace").selectOption(workspaceId);
  await expect(page.getByRole("status")).toHaveCount(0);
  await expect(page.locator("canvas").first()).toBeVisible();
  await page.screenshot({ path: "test-results/operational-globe-desktop.png" });
  await page.getByLabel("Operational lens").selectOption("global");
  await expect(page.getByLabel("Operational workspace")).toHaveCount(0);
  expect(errors).toEqual([]);
});
